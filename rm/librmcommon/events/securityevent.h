#ifndef SECURITYEVENT_H
#define SECURITYEVENT_H

#include "baseevent.h"
#include <sys/types.h>
#include <iostream>

namespace rmcommon {

/*!
\class event generated by the Konro server when a security event
is received for a process.
 */
class SecurityEvent : public BaseEvent {

    pid_t pid_;

public:

    SecurityEvent(pid_t pid) :
        BaseEvent("SecurityEvent"),
        pid_(pid) {}

    pid_t getPid() const {
        return pid_;
    }

    void printOnOstream(std::ostream &os) const override {
        os << "{\"pid\":" << static_cast<long>(pid_) << "}";
    }
};

}   // namespace rmcommon
#endif // SECURITYEVENT_H